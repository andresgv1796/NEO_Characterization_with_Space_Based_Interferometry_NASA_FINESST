function primaryPath = save_study_figure( ...
    fig,folder,baseName,savePNG,pngResolution,saveFIG,savePDF)
%SAVE_STUDY_FIGURE Save one study figure without embedding graphics
% handles in the MAT results structure.
%
% Returns the primary saved path (PNG when enabled, otherwise FIG/PDF).

    primaryPath = "";

    if savePNG

        pngPath = ...
            fullfile(folder,[baseName,'.png']);

        exportgraphics( ...
            fig, ...
            pngPath, ...
            'Resolution',pngResolution);

        primaryPath = string(pngPath);

    end


    if saveFIG

        figPath = ...
            fullfile(folder,[baseName,'.fig']);

        savefig(fig,figPath);

        if strlength(primaryPath)==0
            primaryPath = string(figPath);
        end

    end


    if savePDF

        pdfPath = ...
            fullfile(folder,[baseName,'.pdf']);

        exportgraphics( ...
            fig, ...
            pdfPath, ...
            'ContentType','vector');

        if strlength(primaryPath)==0
            primaryPath = string(pdfPath);
        end

    end

end
