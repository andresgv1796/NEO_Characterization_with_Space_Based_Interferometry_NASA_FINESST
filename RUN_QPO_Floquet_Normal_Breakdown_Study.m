%% ============================================================
%  5A. NORMAL-PLANE SUSCEPTIBILITY VERSUS FLOQUET CIRCULARITY
%  ============================================================

nSummaryParents = height(parentSummaryTable);

Kn_deg_per_km = nan(nSummaryParents,1);
nKnPoints = zeros(nSummaryParents,1);


for ip = 1:nSummaryParents

    parentRow = ...
        parentSummaryTable.ParentRow(ip);

    thisParent = ...
        caseTable.ParentRow == parentRow;


    R = ...
        caseTable.TorusRadiusRMS_km(thisParent);

    E50 = ...
        caseTable.NormalTrack_E50_deg(thisParent);


    E0 = ...
        parentSummaryTable.NormalErrorFloor_deg(ip);


    % Remove the fitted numerical floor before estimating the
    % finite-amplitude normal-error susceptibility.
    %
    % From
    %
    %   E50(R) = sqrt(E0^2 + E_nl(R)^2)
    %
    % recover
    %
    %   E_nl(R) = sqrt(E50^2 - E0^2).

    Enonlinear = ...
        sqrt( ...
            max( ...
                E50.^2 - E0.^2, ...
                0));


    % Restrict the coefficient estimate to the pre-breakdown regime.
    % This avoids allowing strongly nonlinear, near-90-deg cases to
    % determine what is intended to be a local susceptibility.
    useKn = ...
        isfinite(R) & ...
        isfinite(E50) & ...
        isfinite(Enonlinear) & ...
        R > 0 & ...
        E50 < 1.0 & ...
        Enonlinear > 0;


    nKnPoints(ip) = ...
        nnz(useKn);


    % Two points are allowed because row 294 currently has only two
    % analyzed cases below the 1-deg threshold.
    if nKnPoints(ip) >= 2

        Kn_deg_per_km(ip) = ...
            median( ...
                Enonlinear(useKn) ./ R(useKn));

    end

end


parentSummaryTable.NormalSusceptibility_Kn_deg_per_km = ...
    Kn_deg_per_km;

parentSummaryTable.NormalSusceptibility_NumPoints = ...
