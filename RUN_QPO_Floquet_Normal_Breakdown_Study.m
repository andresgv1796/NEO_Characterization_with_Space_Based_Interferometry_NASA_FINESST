%% RUN_QPO_Floquet_Normal_Breakdown_Study
%
% FINESST / GMOS
%
% FINITE-QPO BREAKDOWN OF THE LINEAR FLOQUET FORMATION PREDICTOR
%
% Goal
% ----
% Quantify how the exact finite-amplitude three-collector QPO formation
% departs from the parent periodic orbit's linear transported Floquet plane
% as the corrected torus size grows.
%
% This study tests four distinct predictions of the linear model:
%
%   1. Normal-track prediction
%
%          n_QPO(t) -> n_F(t)
%
%      as torus size -> 0.
%
%   2. Phase independence
%
%      In the linear model, all collector phase choices lie in the same
%      transported Floquet plane.  Therefore finite phase spread should
%      vanish as size -> 0.
%
%   3. Parent-period plane closure
%
%          n_F(t+T) = +/- n_F(t)
%
%      exactly in the linear model.  Finite-QPO non-closure measures how
%      strongly higher harmonics make the triangle plane genuinely
%      quasiperiodic.
%
%   4. Linear baseline breathing
%
%      After calibrating the arbitrary Floquet eigenvector scale to the
%      actual corrected QPO section RMS radius, compare finite B_RMS(t)
%      against the linear prediction.
%
% Family construction
% -------------------
% Each parent uses TWO nearby small corrected seeds followed by the existing
% fixed-T pseudo-arclength continuation routine:
%
%       gmos_continue_fixT_family
%
% We deliberately do NOT solve a list of unrelated seed amplitudes because
% independent Newton solves can jump to unrelated QPO branches.
%
% Main outputs
% ------------
% For every analyzed family member:
%
%   actual corrected torus RMS radius [km]
%   median and worst Floquet-normal error across starting phases
%   nonlinear phase-spread metric
%   period-to-period plane non-closure
%   baseline-breathing relative error
%   nonlinear rho departure
%
% The default parent set contains ten representative halo parents spanning
% the catalog-row regime where genuine nontrivial center pairs were found.
%
% For each parent, the script also fits a local power law
%
%       delta_n,RMS ~ C R^p
%
% over the smallest members lying below the configured error ceiling.
%
% Recommended interpretation
% --------------------------
% If p ~ 1, the generic O(R) correction is present.
% If p ~ 2, symmetry cancels the first-order angular correction and the
% linear Floquet surrogate is substantially better than the generic estimate.
%
% Required existing functions
% ---------------------------
%   cr3bp_system_parameters
%   choose_periodic_orbit
%   gmos_demo_invariance_only
%   gmos_pack_z
%   gmos_unpack_z
%   gmos_newton_fixT_analytic
%   gmos_continue_fixT_family
%   qpo_equal_phase_indices
%   compute_three_collector_qpo_geometry
%   monodromy_CR3BP
%   gmos_center_eigpair_from_eigs
%   transport_floquet_center_geometry_CR3BP
%
% New helpers supplied with this study
% ------------------------------------
%   build_gmos_fixedT_amplitude_family
%   evaluate_finite_qpo_vs_floquet

