function idx = choose_radius_distributed_members( ...
    radius_km,maxMembers,nSmallAlways)

    valid = ...
        find( ...
            isfinite(radius_km) & ...
            radius_km > 0);


    if isempty(valid)

        error('No valid positive-radius family members.');

    end


    [rSorted,order] = ...
        sort(radius_km(valid));


    idxSorted = ...
        valid(order);


    nSmallAlways = ...
        min(nSmallAlways,numel(idxSorted));


    mustKeep = ...
        idxSorted(1:nSmallAlways);


    if numel(idxSorted) <= maxMembers

        idx = idxSorted(:).';
        return

    end


    nRemaining = ...
        maxMembers-numel(mustKeep);


    if nRemaining <= 0

        idx = mustKeep(:).';
        return

    end


    rMin = ...
        rSorted(nSmallAlways);

    rMax = ...
        max(rSorted);


    if rMax/rMin >= 3

        targetR = ...
            logspace( ...
                log10(rMin), ...
                log10(rMax), ...
                nRemaining+1);

    else

        targetR = ...
            linspace( ...
                rMin, ...
                rMax, ...
                nRemaining+1);

    end


    targetR = ...
        targetR(2:end);


    extra = zeros(1,numel(targetR));

    for k = 1:numel(targetR)

        [~,j] = ...
            min(abs(rSorted-targetR(k)));

        extra(k) = ...
            idxSorted(j);

    end


    idx = ...
        unique( ...
            [mustKeep(:).',extra,idxSorted(end)], ...
            'stable');

end


function fit = fit_local_power_law( ...
    R,E,errorCeiling,maxPoints,minPoints)

    R = R(:);
    E = E(:);


    valid = ...
        isfinite(R) & ...
        R > 0 & ...
        isfinite(E) & ...
        E > 1e-10;


    idx = ...
        find(valid & E <= errorCeiling);


    if numel(idx) < minPoints

        idx = ...
            find(valid);

    end


    if isempty(idx)

        fit = empty_power_fit();
        return

    end


    [~,sortIdx] = ...
        sort(R(idx));


    idx = ...
        idx(sortIdx);


    idx = ...
        idx(1:min(maxPoints,numel(idx)));


    if numel(idx) < minPoints

        fit = empty_power_fit();
        fit.indices = idx;
        return

    end


    p = ...
        polyfit( ...
            log(R(idx)), ...
            log(E(idx)), ...
            1);


    fit = struct();

    fit.p = p(1);
    fit.C = exp(p(2));

    fit.indices = idx;

    fit.R = R(idx);
    fit.E = E(idx);

    fit.Efit = ...
        fit.C*fit.R.^fit.p;

end



function fit = fit_post_floor_power_law( ...
    R,E,errorCeiling,maxPoints,minPoints)
%FIT_POST_FLOOR_POWER_LAW
% Fit E = C R^p on the resolved rising branch after the numerical floor.

    R = R(:);
    E = E(:);

    valid = ...
        isfinite(R) & R > 0 & ...
        isfinite(E) & E > 0;

    if isfinite(errorCeiling)

        valid = ...
            valid & ...
            E <= errorCeiling;

    end

    idxAll = find(valid);

    if numel(idxAll) < minPoints

        fit = empty_power_fit();
        return

    end

    [~,ord] = sort(R(idxAll));
    idxAll = idxAll(ord);

    [~,iMinLocal] = min(E(idxAll));

    idx = ...
        idxAll(iMinLocal:end);

    if numel(idx) < minPoints

        fit = empty_power_fit();
        fit.indices = idx;
        return

    end

    idx = ...
        idx(1:min(maxPoints,numel(idx)));

    p = ...
        polyfit( ...
            log(R(idx)), ...
            log(E(idx)), ...
            1);

    fit = struct();

    fit.p = p(1);
    fit.C = exp(p(2));

    fit.indices = idx;
    fit.R = R(idx);
    fit.E = E(idx);
    fit.Efit = fit.C*fit.R.^fit.p;

end


