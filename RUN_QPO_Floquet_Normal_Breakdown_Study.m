%% ============================================================
%  1. STUDY CONFIGURATION
%  ============================================================

systemName = 'EarthMoon';

sys = cr3bp_system_parameters(systemName);


poFile = ...
    'L1_northern_halo_orbits_JPL_IC_Earth_Moon.csv';


% Clean progression from modest to much broader Floquet-plane motion.
% Baseline parents from the first study plus three larger-|z0| parents
% that still possess genuine nontrivial unit-circle center candidates in
% the full Floquet survey.
%
%   row 161 : |z0| ~= 0.207 LU, vertical-dominant center candidate
%   row 294 : |z0| ~= 0.288 LU, isolated large-halo center candidate
%   row 296 : |z0| ~= 0.292 LU, isolated large-halo center candidate
%
% NOTE: JPL catalog row is an inventory coordinate, not a continuation
% coordinate.  In particular rows 294--296 belong to an isolated
% center-candidate cluster and should be treated as stress-test cases rather
% than as a smooth continuation of row 197.
% Representative parents spanning the catalog-row regime in which a
% genuine nontrivial center pair exists.  Catalog row is still only an
% inventory coordinate; this is a morphology survey, not a continuation
% diagram of the halo family itself.
%
% Early/main center-candidate run : 20, 60, 82, 125
% End of main run                : 150
% Intermittent later candidates  : 161, 197, 250
% Isolated large-halo candidates : 294, 296
parentRows = [20 60 82 125 150 161 197 250 294 296];


%% GMOS family generation

N = 51;

mode = 'vertical';


% Two small nearby seeds only.  The remaining family comes from continuation.
KSeeds = [1e-5 3e-5];


% Number of PALC steps AFTER the two corrected startup members.
nContinuationSteps = 180;


% PALC step is chosen relative to the corrected startup secant norm:
%
%   ds = multiplier * ||z1-z0||
%
% Start conservatively. Increase only after inspecting family smoothness.
continuationStepMultiplier = 4.0;


newtonOpts = struct();

newtonOpts.maxIter = 20;
newtonOpts.tolInf = 1e-10;
newtonOpts.verbose = false;


odeOpts = odeset( ...
    'RelTol',1e-12, ...
    'AbsTol',1e-12);


%% Formation evaluation

nCollectors = 3;

normalReferenceSynodic = [1 0 0];


% IMPORTANT:
% The finite QPO is propagated for TWO parent periods.
%
%   - the primary Floquet-normal error is evaluated on the FIRST period;
%   - the SECOND period exists only so that one-period plane non-closure can
%     be measured.
%
% The linear Floquet predictor itself is computed over one parent period and
% then treated as periodic as a plane.
nPrimaryPeriods = 2;

nSavePerPrimaryPeriod = 250;


% The full continued family may contain dozens of members.  Analyze a
% radius-distributed subset with all distinct phases.
maxFamilyMembersToAnalyze = 20;

% Always retain the first few corrected family members so the numerical
% floor and the small-amplitude asymptotic regime remain well resolved even
% when the continuation reaches much larger tori.
nSmallMembersToAlwaysAnalyze = 5;


%% Local convergence-law fit

% Floor-aware model used for quantities that visibly approach a finite
% numerical/discretization floor:
%
%   E(R) = sqrt( E_floor^2 + (C R^p)^2 ).
%
% This prevents the floor from biasing p toward zero.
fitMaxErrorDeg = 0.5;

fitMaxPoints = 12;

fitMinPoints = 5;


%% Linear predictor sampling

nFloquetSamples = nSavePerPrimaryPeriod + 1;

nFloquetPhaseSamples = 61;


%% Saving

saveResults = true;

outputDir = fullfile( ...
    pwd, ...
    'QPO_Floquet_Normal_Breakdown_Study');

if ~exist(outputDir,'dir')
    mkdir(outputDir);
end


%% Figure export

saveFigures = true;

% PNG is convenient for reports / quick inspection.
saveFigurePNG = true;
figurePNGResolution = 300;

% MATLAB FIG retains full editability.
saveFigureFIG = true;

% Optional vector PDF.  Disabled by default because sphere/surface figures
% can become large.  Turn on if you want publication-vector exports.
saveFigurePDF = false;


%% ============================================================
%  2. GLOBAL STORAGE
%  ============================================================

nParents = numel(parentRows);

parentResults = cell(nParents,1);

parentSucceeded = false(nParents,1);
parentFailureMessage = strings(nParents,1);

allRows = {};


%% ============================================================
%  3. PARENT LOOP
%  ============================================================

for ip = 1:nParents

    orbitIndex = parentRows(ip);


    fprintf('\n');
    fprintf('============================================================\n');
    fprintf('PARENT %d / %d : JPL ROW %d\n', ...
        ip,nParents,orbitIndex);
    fprintf('============================================================\n');


    po = choose_periodic_orbit( ...
        poFile, ...
        orbitIndex, ...
        sys);

    fprintf('Parent z0                 = %.9f LU\n',po.x0(3));
    fprintf('Parent |z0|               = %.9f LU\n',abs(po.x0(3)));
    fprintf('Parent period             = %.9f TU\n',po.T);


    %% --------------------------------------------------------
    %  3.1 Linear Floquet predictor for this parent
    %  --------------------------------------------------------

    M_eigs = monodromy_CR3BP( ...
        [0,po.T], ...
        po.x0(:), ...
        sys.mu);


    V = M_eigs(:,1:6);
    D = M_eigs(:,7:12);


    centerOpts = struct();

    centerOpts.tolUnit = 1e-6;
    centerOpts.tolImag = 1e-10;
    centerOpts.warnMismatch = false;


    cen = gmos_center_eigpair_from_eigs( ...
        V, ...
        D, ...
        mode, ...
        centerOpts);


    floquetGeom = ...
        transport_floquet_center_geometry_CR3BP( ...
            [0,po.T], ...
            po.x0(:), ...
            sys.mu, ...
            cen.w, ...
            nFloquetSamples, ...
            odeOpts, ...
            nFloquetPhaseSamples);


    fprintf('Linear center rho/(2pi) = %.8f cycles\n', ...
        cen.rho0_cycles);

    fprintf('Floquet normal RMS excursion = %.6f deg\n', ...
        floquetGeom.metrics.synodic.RMSExcursion_deg);


    %% --------------------------------------------------------
    %  3.2 Build ONE continuous fixed-T finite-QPO family
    %  --------------------------------------------------------

    try

        family = ...
            build_gmos_fixedT_amplitude_family( ...
                po, ...
                sys, ...
                N, ...
                KSeeds, ...
                mode, ...
                nContinuationSteps, ...
                continuationStepMultiplier, ...
                odeOpts, ...
                newtonOpts);

    catch ME

        warning( ...
            ['Skipping parent row %d because the finite-QPO startup / ', ...
             'continuation family could not be constructed:%s'], ...
            orbitIndex, ...
            ME.message);

        parentFailureMessage(ip) = ...
            string(ME.message);

        failedParent = struct();

        failedParent.orbitIndex = orbitIndex;
        failedParent.po = po;
        failedParent.cen = cen;
        failedParent.floquetGeom = floquetGeom;
        failedParent.failed = true;
        failedParent.failureMessage = string(ME.message);

        parentResults{ip} = failedParent;

        continue

    end


    nFamily = numel(family.fam.z);


    fprintf('Accepted family members = %d\n',nFamily);
    fprintf('Continuation ds         = %.6e\n',family.ds);

    fprintf('Radius range             = %.6g to %.6g km\n', ...
        min(family.radiusRMS_km), ...
        max(family.radiusRMS_km));

    fprintf('Jacobi analysis limit    = %.3e\n', ...
        family.jacobiLimit);

    fprintf('Resolution-valid members = %d / %d\n', ...
        nnz(family.analysisValid), ...
        numel(family.analysisValid));


    %% --------------------------------------------------------
    %  3.3 Choose family members distributed across ACTUAL radius
    %  --------------------------------------------------------

    radiusForSelection = ...
        family.radiusRMS_km;

    radiusForSelection(~family.analysisValid) = ...
        NaN;


    familyIdx = ...
        choose_radius_distributed_members( ...
            radiusForSelection, ...
            maxFamilyMembersToAnalyze, ...
            nSmallMembersToAlwaysAnalyze);


    fprintf('Analyzing family indices: ');
    fprintf('%d ',familyIdx);
    fprintf('\n');


    %% Physically distinct common starting phases

    phaseStartIndices = ...
        unique_equal_phase_start_indices( ...
            N, ...
            nCollectors);


    fprintf('Distinct 3-collector phase cases = %d\n', ...
        numel(phaseStartIndices));


    %% --------------------------------------------------------
    %  3.4 Evaluate selected finite tori
    %  --------------------------------------------------------

    nCases = numel(familyIdx);

    caseResults = cell(nCases,1);


    for ic = 1:nCases

        iFam = familyIdx(ic);


        [XCurve,TQPO,rhoQPO] = ...
            gmos_unpack_z( ...
                family.fam.z{iFam}, ...
                N);


        fprintf('\n');
        fprintf('  family member %d/%d (family index %d)\n', ...
            ic,nCases,iFam);

        fprintf('    R_rms = %.6f km\n', ...
            family.radiusRMS_km(iFam));

        fprintf('    rho/(2pi) = %.10f\n', ...
            rhoQPO/(2*pi));


        result = ...
            evaluate_finite_qpo_vs_floquet( ...
                XCurve, ...
                TQPO, ...
                rhoQPO, ...
                po, ...
                sys, ...
                floquetGeom, ...
                nCollectors, ...
                phaseStartIndices, ...
                nPrimaryPeriods, ...
                nSavePerPrimaryPeriod, ...
                odeOpts, ...
                normalReferenceSynodic);


        result.familyIndex = iFam;
        result.jacobiSpread = family.jacobiSpread(iFam);

        caseResults{ic} = result;


        allRows(end+1,:) = { ...
            orbitIndex, ...
            iFam, ...
            result.sectionRadiusRMS_km, ...
            rhoQPO/(2*pi), ...
            result.rhoError_rad, ...
            family.jacobiSpread(iFam), ...
            result.summary.normalTrackE50_deg, ...
            result.summary.normalTrackE95_deg, ...
            result.summary.normalTrackEmax_deg, ...
            result.summary.qAMinFirst, ...
            result.phaseSpreadRMS_deg, ...
            result.summary.periodClosureMedianRMS_deg, ...
            result.summary.baselineRelErrorMedianRMS, ...
            result.summary.medianBaseline_km};

    end


    %% --------------------------------------------------------
    %  3.5 Sort analyzed cases by actual physical radius
    %  --------------------------------------------------------

    radius_km = ...
        cellfun( ...
            @(x) x.sectionRadiusRMS_km, ...
            caseResults);


    [radius_km,sortIdx] = ...
        sort(radius_km);


    caseResults = ...
        caseResults(sortIdx);


    familyIdxSorted = ...
        familyIdx(sortIdx);


    %% --------------------------------------------------------
    %  3.6 Power-law fits in the small-error regime
    %  --------------------------------------------------------

    normalMedian = ...
        cellfun( ...
            @(x) x.summary.normalTrackE50_deg, ...
            caseResults);


    phaseSpread = ...
        cellfun( ...
            @(x) x.phaseSpreadRMS_deg, ...
            caseResults);


    periodClosure = ...
        cellfun( ...
            @(x) x.summary.periodClosureMedianRMS_deg, ...
            caseResults);


    baselineError = ...
        cellfun( ...
            @(x) x.summary.baselineRelErrorMedianRMS, ...
            caseResults);


    rhoError = ...
        cellfun( ...
            @(x) x.rhoError_rad, ...
            caseResults);


    % The raw normal error contains a clear parent-dependent floor.  Fit
    %
    %   E(R) = sqrt(E_floor^2 + (C R^p)^2)
    %
    % rather than E = C R^p.
    fitNormal = ...
        fit_floor_power_law( ...
            radius_km, ...
            normalMedian, ...
            fitMaxErrorDeg, ...
            fitMaxPoints, ...
            fitMinPoints);


    % Phase spread and period non-closure are zero in the exact linear
    % model.  Very small finite formations can nevertheless be dominated by
    % numerical differencing / propagation noise.  Fit only the resolved
    % rising branch after the observed minimum.
    fitPhase = ...
        fit_post_floor_power_law( ...
            radius_km, ...
            phaseSpread, ...
            fitMaxErrorDeg, ...
            fitMaxPoints, ...
            fitMinPoints);


    fitClosure = ...
        fit_post_floor_power_law( ...
            radius_km, ...
            periodClosure, ...
            fitMaxErrorDeg, ...
            fitMaxPoints, ...
            fitMinPoints);


    % Baseline-relative error visibly has a finite floor from interpolation /
    % finite discretization, so fit it with the same floor-aware model.
    fitBaseline = ...
        fit_floor_power_law( ...
            radius_km, ...
            baselineError, ...
            Inf, ...
            fitMaxPoints, ...
            fitMinPoints);


    % Rotation-number departure should be quadratic in amplitude, but the
    % very smallest corrected tori can be dominated by numerical scatter.
    % Detect the minimum-error floor automatically and fit only the rising
    % post-floor branch.  This fixes cases such as row 161 without adding a
    % user-tuned threshold.
    fitRho = ...
        fit_post_floor_power_law( ...
            radius_km, ...
            rhoError, ...
            Inf, ...
            fitMaxPoints, ...
            fitMinPoints);


    %% Validity radii for simple angular tolerances
    %
    % If the threshold is never crossed, report the largest tested radius as
    % a LOWER BOUND rather than pretending it is the actual validity limit.

    valid1 = ...
        estimate_error_threshold( ...
            radius_km, ...
            normalMedian, ...
            1.0);


    valid5 = ...
        estimate_error_threshold( ...
            radius_km, ...
            normalMedian, ...
            5.0);


    fprintf('\nParent row %d summary\n',orbitIndex);

    fprintf('  fitted normal-error floor E0 = %.6e deg\n', ...
        fitNormal.floor);

    fprintf('  floor-corrected normal power p = %.6f\n', ...
        fitNormal.p);

    fprintf('  post-floor phase-spread power p= %.6f\n', ...
        fitPhase.p);

    fprintf('  post-floor closure power p     = %.6f\n', ...
        fitClosure.p);

    fprintf('  fitted baseline-error floor    = %.6e\n', ...
        fitBaseline.floor);

    fprintf('  baseline nonlinear power p     = %.6f\n', ...
        fitBaseline.p);

    fprintf('  rotation-number power p        = %.6f\n', ...
        fitRho.p);

    print_threshold_result('1 deg',valid1);
    print_threshold_result('5 deg',valid5);


    %% --------------------------------------------------------
    %  3.7 Parent plots
    %  --------------------------------------------------------

    fig1 = ...
        make_parent_error_scaling_figure( ...
            orbitIndex, ...
            radius_km, ...
            caseResults, ...
            fitNormal, ...
            fitPhase, ...
            fitClosure, ...
            fitBaseline, ...
            fitRho);


    fig2 = ...
        make_parent_phase_heatmap_figure( ...
            orbitIndex, ...
            radius_km, ...
            caseResults);


    fig3 = ...
        make_parent_normal_track_comparison_figure( ...
            orbitIndex, ...
            radius_km, ...
            caseResults);


    fig4 = ...
        make_parent_family_diagnostics_figure( ...
            orbitIndex, ...
            family, ...
            familyIdxSorted);


    %% --------------------------------------------------------
    %  3.8 Save parent figures
    %  --------------------------------------------------------

    parentFigureFiles = strings(4,1);

    if saveFigures

        parentFigureDir = ...
            fullfile( ...
                outputDir, ...
                sprintf('ParentRow_%03d_Figures',orbitIndex));

        if ~exist(parentFigureDir,'dir')
            mkdir(parentFigureDir);
        end

        parentFigureFiles(1) = ...
            save_study_figure( ...
                fig1, ...
                parentFigureDir, ...
                sprintf('Row_%03d_breakdown_scaling',orbitIndex), ...
                saveFigurePNG, ...
                figurePNGResolution, ...
                saveFigureFIG, ...
                saveFigurePDF);

        parentFigureFiles(2) = ...
            save_study_figure( ...
                fig2, ...
                parentFigureDir, ...
                sprintf('Row_%03d_phase_size_heatmaps',orbitIndex), ...
                saveFigurePNG, ...
                figurePNGResolution, ...
                saveFigureFIG, ...
                saveFigurePDF);

        parentFigureFiles(3) = ...
            save_study_figure( ...
                fig3, ...
                parentFigureDir, ...
                sprintf('Row_%03d_normal_track_comparison',orbitIndex), ...
                saveFigurePNG, ...
                figurePNGResolution, ...
                saveFigureFIG, ...
                saveFigurePDF);

        parentFigureFiles(4) = ...
            save_study_figure( ...
                fig4, ...
                parentFigureDir, ...
                sprintf('Row_%03d_continuation_diagnostics',orbitIndex), ...
                saveFigurePNG, ...
                figurePNGResolution, ...
                saveFigureFIG, ...
                saveFigurePDF);

    end


    %% --------------------------------------------------------
    %  3.9 Store parent result
    %  --------------------------------------------------------

    parentResult = struct();

    parentResult.orbitIndex = orbitIndex;

    parentResult.po = po;

    parentResult.cen = cen;

    parentResult.floquetGeom = floquetGeom;

    parentResult.family = family;

    parentResult.familyIdxAnalyzed = familyIdxSorted;

    parentResult.caseResults = caseResults;

    parentResult.fitNormal = fitNormal;
    parentResult.fitPhase = fitPhase;
    parentResult.fitClosure = fitClosure;
    parentResult.fitBaseline = fitBaseline;
    parentResult.fitRho = fitRho;

    parentResult.validity1deg = valid1;
    parentResult.validity5deg = valid5;

    % Store filenames only.  Do NOT store graphics handles in the MAT
    % file; doing so greatly inflates the MAT file and triggers MATLAB's
    % graphics-object warning.
    parentResult.figureFiles = parentFigureFiles;

    parentResults{ip} = parentResult;
    parentSucceeded(ip) = true;

end


