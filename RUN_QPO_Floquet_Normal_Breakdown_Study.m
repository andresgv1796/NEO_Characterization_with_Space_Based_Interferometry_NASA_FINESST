function fit = fit_floor_power_law( ...
    R,E,errorCeiling,maxPoints,minPoints)
%FIT_FLOOR_POWER_LAW
%
% Fit
%
%   E(R) = sqrt(E_floor^2 + (C R^p)^2)
%
% in log-error space.  All three fitted quantities are constrained positive
% by optimizing their logarithms.

    R = R(:);
    E = E(:);

    valid = ...
        isfinite(R) & ...
        R > 0 & ...
        isfinite(E) & ...
        E > 0;

    if isfinite(errorCeiling)

        valid = ...
            valid & ...
            E <= errorCeiling;

    end

    idx = find(valid);

    if numel(idx) < minPoints

        idx = find( ...
            isfinite(R) & R > 0 & ...
            isfinite(E) & E > 0);

    end

    if isempty(idx)

        fit = empty_floor_fit();
        return

    end

    [~,ord] = sort(R(idx));
    idx = idx(ord);

    idx = ...
        idx(1:min(maxPoints,numel(idx)));

    if numel(idx) < minPoints

        fit = empty_floor_fit();
        fit.indices = idx;
        return

    end

    Rf = R(idx);
    Ef = E(idx);

    floor0 = ...
        max(0.8*min(Ef),realmin);

    nonlinearTop = ...
        sqrt( ...
            max( ...
                max(Ef)^2-floor0^2, ...
                (0.1*max(Ef))^2));

    C0 = ...
        max( ...
            nonlinearTop/max(Rf), ...
            realmin);

    p0 = 1.0;

    theta0 = ...
        log([floor0,C0,p0]);

    objective = ...
        @(theta) floor_power_objective(theta,Rf,Ef);

    options = optimset( ...
        'Display','off', ...
        'TolX',1e-10, ...
        'TolFun',1e-12, ...
        'MaxIter',2000, ...
        'MaxFunEvals',5000);

    theta = ...
        fminsearch( ...
            objective, ...
            theta0, ...
            options);

    pars = exp(theta);

    fit = struct();

    fit.floor = pars(1);
    fit.C = pars(2);
    fit.p = pars(3);

    fit.indices = idx;
    fit.R = Rf;
    fit.E = Ef;

    fit.Efit = ...
        floor_power_model( ...
            fit.floor, ...
            fit.C, ...
            fit.p, ...
            fit.R);

    fit.nonlinearComponent = ...
        fit.C*fit.R.^fit.p;

end


function J = floor_power_objective(theta,R,E)

    pars = exp(theta);

    Epred = ...
        floor_power_model( ...
            pars(1), ...
            pars(2), ...
            pars(3), ...
            R);

    residual = ...
        log(Epred)-log(E);

    J = ...
        sum(residual.^2);

end


function E = floor_power_model(Efloor,C,p,R)

    E = ...
        sqrt( ...
            Efloor.^2 + ...
            (C.*R.^p).^2);

end


function fit = empty_floor_fit()

    fit = struct();

    fit.floor = NaN;
    fit.C = NaN;
    fit.p = NaN;

    fit.indices = [];
    fit.R = [];
    fit.E = [];
    fit.Efit = [];
    fit.nonlinearComponent = [];

end


function result = estimate_error_threshold(R,E,tol)
%ESTIMATE_ERROR_THRESHOLD
% If the sampled curve crosses tol, interpolate in log(R)-log(E) between
% the first bracketing pair.  Otherwise return the largest tested acceptable
% radius as a lower bound.

    R = R(:);
    E = E(:);

    valid = ...
        isfinite(R) & ...
        R > 0 & ...
        isfinite(E) & ...
        E >= 0;

    R = R(valid);
    E = E(valid);

    [R,ord] = sort(R);
    E = E(ord);

    result = struct();

    result.tolerance = tol;
    result.crossed = false;
    result.radiusEstimate_km = NaN;
    result.lowerBound_km = NaN;

    if isempty(R)
        return
    end

    below = E <= tol;

    if any(below)

        result.lowerBound_km = ...
            max(R(below));

    end

    iCross = ...
        find(E > tol,1,'first');

    if isempty(iCross)

        % No observed crossing: the largest tested acceptable radius is only
        % a lower bound on the actual validity limit.
        return

    end

    if iCross == 1

        result.crossed = true;
        result.radiusEstimate_km = R(1);
        return

    end

    i0 = iCross-1;

    if E(i0) <= 0 || E(iCross) <= 0

        Rcross = ...
            interp1( ...
                E([i0,iCross]), ...
                R([i0,iCross]), ...
                tol);

    else

        logR = ...
            interp1( ...
                log(E([i0,iCross])), ...
                log(R([i0,iCross])), ...
                log(tol));

        Rcross = exp(logR);

    end

    result.crossed = true;
    result.radiusEstimate_km = Rcross;

end


function print_threshold_result(label,result)

    if result.crossed

        fprintf('  estimated R at median normal error = %s : %.6g km\\n', ...
            label, ...
            result.radiusEstimate_km);

    else

        fprintf(['  median normal error never reached %s; ', ...
                 'validity radius > %.6g km (tested lower bound)\\n'], ...
            label, ...
            result.lowerBound_km);

    end

end


function Rmax = largest_radius_below_error(R,E,tolDeg)

    valid = ...
        isfinite(R) & ...
        isfinite(E) & ...
        E <= tolDeg;


    if any(valid)

        Rmax = max(R(valid));

    else

        Rmax = NaN;

    end

end


