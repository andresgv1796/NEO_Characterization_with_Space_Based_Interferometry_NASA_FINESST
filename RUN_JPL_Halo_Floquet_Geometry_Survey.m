                continue
            end

            fg = trackStore{kk};

            switch panel

                case 1

                    y = fg.positionVerticalFraction;
                    yLabel = '$f_{v,\mathrm{pos}}$';
                    ttl = 'Transported position-space vertical fraction';

                case 2

                    y = fg.circularity;
                    yLabel = '$\chi=\sigma_2/\sigma_1$';
                    ttl = 'Instantaneous center-ellipse circularity';

                case 3

                    y = fg.positionRMSRadius / ...
                        median(fg.positionRMSRadius,'omitnan');

                    yLabel = '$R_F/\mathrm{median}(R_F)$';
                    ttl = 'Scale-free baseline breathing';

                case 4

                    nMean = fg.metrics.synodic.meanAxis;

                    c = abs(fg.nSynodic*nMean.');

                    c = min(1,max(-1,c));

                    y = acosd(c);

                    yLabel = 'normal excursion [deg]';
                    ttl = 'Plane-normal excursion from mean axis';

            end

            plot( ...
                ax, ...
                fg.tau, ...
                y, ...
                'Color',colors(j,:), ...
                'DisplayName',sprintf('row %d',row));

        end

        xlabel(ax,'$t/T$');
        ylabel(ax,yLabel);
        title(ax,ttl);

        if panel == 1
            legend(ax,'Location','best');
