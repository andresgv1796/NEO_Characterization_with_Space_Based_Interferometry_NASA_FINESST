%% ============================================================
%  4. RUN THE LINEAR GEOMETRY SURVEY
%  ============================================================

runParallel = false;

if useParallel

    try

        if license('test','Distrib_Computing_Toolbox')

            pool = gcp('nocreate');

            if isempty(pool)
                parpool;
            end

            runParallel = true;

        end

    catch ME

        warning( ...
            'Parallel setup failed; using serial loop: %s', ...
            ME.message);

    end

end


fprintf('\nTransporting center Floquet modes...\n');

tic;


if runParallel

    parfor kk = 1:nCandidates

        row = candidateRows(kk);

        try

            x0 = X0Catalog(row,:).';
            T = periodTU(row);
            mu = muCatalog(row);

            M_eigs = monodromy_CR3BP([0,T],x0,mu);

            V = M_eigs(:,1:6);
            D = M_eigs(:,7:12);

            cen = gmos_center_eigpair_from_eigs( ...
                V, ...
                D, ...
                centerMode, ...
                centerOpts);

            fg = transport_floquet_center_geometry_CR3BP( ...
                [0,T], ...
                x0, ...
                mu, ...
                cen.w, ...
                nTimeSamples, ...
                odeOpts, ...
                nPhaseSamples);

            rhoCycles(kk) = cen.rho0_cycles;

            initialStateVerticalFraction(kk) = ...
                cen.proj.verticalFraction;

            initialPositionVerticalFraction(kk) = ...
                cen.proj.positionVerticalFraction;

            initialVelocityVerticalFraction(kk) = ...
                cen.proj.velocityVerticalFraction;

            meanPositionVerticalFraction(kk) = ...
                fg.metrics.meanPositionVerticalFraction;

            maxPositionVerticalFraction(kk) = ...
                fg.metrics.maxPositionVerticalFraction;

            meanStateVerticalFraction(kk) = ...
                fg.metrics.meanStateVerticalFraction;

            meanVelocityVerticalFraction(kk) = ...
                fg.metrics.meanVelocityVerticalFraction;

            medianCircularity(kk) = ...
                fg.metrics.medianCircularity;

            minCircularity(kk) = ...
                fg.metrics.minCircularity;

            medianEllipseAspect(kk) = ...
                fg.metrics.medianEllipseAspect;

            maxEllipseAspect(kk) = ...
                fg.metrics.maxEllipseAspect;

            positionBreathingRatio(kk) = ...
                fg.metrics.positionBreathingRatio;

            medianPhaseAspect(kk) = ...
                fg.metrics.medianPhaseAspect;

            maxPhaseAspect(kk) = ...
                fg.metrics.maxPhaseAspect;

            normalSynRMS_deg(kk) = ...
                fg.metrics.synodic.RMSExcursion_deg;

            normalSynMax_deg(kk) = ...
                fg.metrics.synodic.maxExcursion_deg;

            normalSynPath_deg(kk) = ...
                fg.metrics.synodic.pathLength_deg;

            normalInertialRMS_deg(kk) = ...
                fg.metrics.inertial.RMSExcursion_deg;

            normalInertialMax_deg(kk) = ...
                fg.metrics.inertial.maxExcursion_deg;

            normalInertialPath_deg(kk) = ...
                fg.metrics.inertial.pathLength_deg;

            normalClosure_deg(kk) = ...
                fg.normalClosure_deg;

            floquetClosureResidual(kk) = ...
                fg.floquetClosureResidual;

            baselineIdentityRelError(kk) = ...
                fg.metrics.maxBaselineIdentityRelError;

            trackStore{kk} = fg;

            success(kk) = true;

        catch ME

            success(kk) = false;
            failureMessage{kk} = ME.message;

        end

    end


else

    for kk = 1:nCandidates

        row = candidateRows(kk);

        if mod(kk,25)==1 || kk==nCandidates

            fprintf('  candidate %d / %d (catalog row %d)\n', ...
                kk,nCandidates,row);

        end

        try

            x0 = X0Catalog(row,:).';
            T = periodTU(row);
            mu = muCatalog(row);

            M_eigs = monodromy_CR3BP([0,T],x0,mu);

            V = M_eigs(:,1:6);
            D = M_eigs(:,7:12);

            cen = gmos_center_eigpair_from_eigs( ...
                V,D,centerMode,centerOpts);

            fg = transport_floquet_center_geometry_CR3BP( ...
                [0,T],x0,mu,cen.w, ...
                nTimeSamples,odeOpts,nPhaseSamples);

            rhoCycles(kk) = cen.rho0_cycles;

            initialStateVerticalFraction(kk) = cen.proj.verticalFraction;
            initialPositionVerticalFraction(kk) = cen.proj.positionVerticalFraction;
            initialVelocityVerticalFraction(kk) = cen.proj.velocityVerticalFraction;

            meanPositionVerticalFraction(kk) = fg.metrics.meanPositionVerticalFraction;
            maxPositionVerticalFraction(kk) = fg.metrics.maxPositionVerticalFraction;

            meanStateVerticalFraction(kk) = fg.metrics.meanStateVerticalFraction;
            meanVelocityVerticalFraction(kk) = fg.metrics.meanVelocityVerticalFraction;

            medianCircularity(kk) = fg.metrics.medianCircularity;
            minCircularity(kk) = fg.metrics.minCircularity;

            medianEllipseAspect(kk) = fg.metrics.medianEllipseAspect;
            maxEllipseAspect(kk) = fg.metrics.maxEllipseAspect;

            positionBreathingRatio(kk) = fg.metrics.positionBreathingRatio;

            medianPhaseAspect(kk) = fg.metrics.medianPhaseAspect;
            maxPhaseAspect(kk) = fg.metrics.maxPhaseAspect;

            normalSynRMS_deg(kk) = fg.metrics.synodic.RMSExcursion_deg;
            normalSynMax_deg(kk) = fg.metrics.synodic.maxExcursion_deg;
            normalSynPath_deg(kk) = fg.metrics.synodic.pathLength_deg;

            normalInertialRMS_deg(kk) = fg.metrics.inertial.RMSExcursion_deg;
            normalInertialMax_deg(kk) = fg.metrics.inertial.maxExcursion_deg;
            normalInertialPath_deg(kk) = fg.metrics.inertial.pathLength_deg;

            normalClosure_deg(kk) = fg.normalClosure_deg;
            floquetClosureResidual(kk) = fg.floquetClosureResidual;
            baselineIdentityRelError(kk) = fg.metrics.maxBaselineIdentityRelError;

            trackStore{kk} = fg;

            success(kk) = true;

        catch ME

            success(kk) = false;
            failureMessage{kk} = ME.message;

        end

    end

end


runtime_s = toc;


fprintf('\nRuntime = %.3f s\n',runtime_s);
fprintf('Successful transported modes = %d / %d\n', ...
    nnz(success),nCandidates);


