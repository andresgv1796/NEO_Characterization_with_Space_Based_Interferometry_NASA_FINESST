%% RUN_JPL_Halo_Floquet_Geometry_Survey
%
% FINESST / GMOS
% Linear Floquet predictor of three-collector QPO formation morphology.
%
% Scientific question
% -------------------
% Can we predict the essential formation behavior directly from the parent
% periodic orbit's center Floquet mode, before generating a finite-amplitude
% QPO?
%
% For every catalog orbit with a genuine nontrivial center pair, this script
% transports the selected complex Floquet eigenvector around one parent
% period:
%
%       w(t) = Phi(t,0) w0.
%
% Writing the position component as
%
%       w_r(t) = a(t) + i b(t),
%
% the first-order center ellipse is
%
%       delta r(t,theta)
%       = a(t) cos(theta) - b(t) sin(theta).
%
% This immediately gives:
%
%       Floquet plane normal:
%           n_F ~ a x b
%
%       ellipse circularity:
%           chi = sigma_2/sigma_1
%
%       position RMS scale:
%           R_F = ||[a,-b]||_F/sqrt(2)
%
% and, for three equal-phase collectors separated by 120 deg,
%
%       B_RMS = sqrt(3) R_F
%
% exactly in the linearized model.
%
% The survey therefore produces a small set of physically interpretable
% predictors:
%
%   Normal excursion       -> pointing / accessibility morphology
%   Ellipse circularity    -> sensitivity to common collector phase
%   Position breathing     -> baseline-scale variation around the PO
%   rho0/(2pi)             -> center-phase advance per parent period
%
% Importantly, these quantities are independent of arbitrary Floquet
% eigenvector phase and, except for absolute R_F, independent of eigenvector
% normalization.
%
% Required existing FINESST functions
% -----------------------------------
%   monodromy_CR3BP
%   gmos_center_eigpair_from_eigs
%   STM_vec
%
% New helper
% ----------
%   transport_floquet_center_geometry_CR3BP
%
% This is a LINEAR predictor study. It does not generate GMOS tori and does
% not run interferometric imaging.  The next validation step is to compare
% these predicted normal tracks with small finite-amplitude QPO formations.

