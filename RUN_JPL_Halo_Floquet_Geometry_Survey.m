%% ============================================================
%  1. CONFIGURATION
%  ============================================================

catalogFile = ...
    'L1_northern_halo_orbits_JPL_IC_Earth_Moon.csv';


% Prefer the clean Floquet-survey output generated by the preceding study.
summaryFileCandidates = { ...
    fullfile( ...
        pwd, ...
        'JPL_Halo_Floquet_Survey', ...
        'JPL_Halo_Floquet_Summary.csv'), ...
    fullfile( ...
        pwd, ...
        'JPL_Halo_Floquet_Summary.csv')};


summaryFile = '';

for k = 1:numel(summaryFileCandidates)

    if isfile(summaryFileCandidates{k})

        summaryFile = ...
            summaryFileCandidates{k};

        break

    end

end


if isempty(summaryFile)

    error( ...
        ['Could not find JPL_Halo_Floquet_Summary.csv. ', ...
         'Run the cleaned whole-family Floquet survey first.']);

end


% Floquet-center selection.
centerMode = 'vertical';

centerOpts = struct();
centerOpts.tolUnit = 1e-6;
centerOpts.tolImag = 1e-10;
centerOpts.warnMismatch = false;


% One parent period is sufficient because the transported Floquet plane
% closes after one period up to the center rotation exp(i*rho0).
nTimeSamples = 401;


% Common center phases used only to measure the linearized triangle-shape
% sensitivity inside each instantaneous center ellipse.
nPhaseSamples = 61;


odeOpts = odeset( ...
    'RelTol',1e-12, ...
    'AbsTol',1e-12);


useParallel = true;


% Representative rows from the earlier morphology studies.
highlightRows = [40 82 125 197 294 296];


saveResults = true;

outputDir = fullfile( ...
    pwd, ...
    'JPL_Halo_Floquet_Geometry_Survey');

if ~exist(outputDir,'dir')
    mkdir(outputDir);
end


%% ============================================================
%  2. READ CATALOG + CLEAN FLOQUET INVENTORY
%  ============================================================

catalogOpts = detectImportOptions( ...
    catalogFile, ...
    'VariableNamingRule','preserve');


catalog = readtable( ...
    catalogFile, ...
    catalogOpts);


X0Catalog = catalog{:,2:7};
periodTU = catalog{:,9};
periodDays = catalog{:,10};
muCatalog = catalog{:,12};


summaryOpts = detectImportOptions( ...
    summaryFile, ...
    'VariableNamingRule','preserve');


summary = readtable( ...
    summaryFile, ...
    summaryOpts);


candidateMask = ...
    to_logical_column( ...
        summary.GMOSWouldFindCenter);


candidateRows = ...
    summary.CatalogRow(candidateMask);


candidateRows = ...
    candidateRows(:);


nCandidates = ...
    numel(candidateRows);


fprintf('\n');
fprintf('============================================================\n');
fprintf('LINEAR FLOQUET FORMATION-PREDICTOR SURVEY\n');
fprintf('============================================================\n');

fprintf('Catalog                   : %s\n',catalogFile);
fprintf('Floquet summary           : %s\n',summaryFile);
fprintf('Genuine center candidates : %d\n',nCandidates);
fprintf('Time samples / period     : %d\n',nTimeSamples);
fprintf('Triangle phase samples    : %d\n',nPhaseSamples);


%% ============================================================
%  3. STORAGE
%  ============================================================

