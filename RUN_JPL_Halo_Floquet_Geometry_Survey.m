function x = to_logical_column(x)
%TO_LOGICAL_COLUMN

    if islogical(x)
        return
    end

    if isnumeric(x)

        x = x ~= 0;
        return

    end

    if iscell(x)

        x = string(x);

    end

    if isstring(x) || ischar(x)

        x = strcmpi(string(x),"true") | ...
            strcmpi(string(x),"1");

        return

    end

    error('Unsupported logical-column type.');

end


function add_highlight_rows(ax,rows)
%ADD_HIGHLIGHT_ROWS

    hold(ax,'on');

    for r = rows(:).'

        xline( ...
            ax, ...
            r, ...
            ':', ...
            sprintf('%d',r), ...
            'LabelVerticalAlignment','bottom', ...
            'HandleVisibility','off');

    end

end
